CREATE TABLE IF NOT EXISTS progreso_estudiante
(
    codigo_materia VARCHAR(20) PRIMARY KEY,

    aprobada BOOLEAN NOT NULL DEFAULT FALSE,

    fecha_actualizacion TIMESTAMP
        NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS seleccion_electiva
(
    id INT PRIMARY KEY,

    codigo_electiva VARCHAR(20),

    fecha_actualizacion TIMESTAMP
        NOT NULL DEFAULT CURRENT_TIMESTAMP
);


CREATE TABLE IF NOT EXISTS cambios_pensum
(
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        PRIMARY KEY,

    operacion VARCHAR(30) NOT NULL,

    codigo VARCHAR(20) NOT NULL,

    destino VARCHAR(20),

    nombre VARCHAR(250),

    uv INT,

    ciclo INT,

    area VARCHAR(100),

    obligatoria BOOLEAN,

    fecha_actualizacion TIMESTAMP
        NOT NULL DEFAULT CURRENT_TIMESTAMP
);
